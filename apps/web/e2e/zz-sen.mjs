import { chromium, devices } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices['Pixel 7'], viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
const p = await ctx.newPage();
await p.goto('http://localhost:4173/?state=loading&look=minted&mode=light');
await p.waitForTimeout(800);
console.log(await p.evaluate(() => (() => { const a = document.querySelector('a[data-k=review]'); return JSON.stringify([a.textContent, a.getAttribute('aria-label'), a.innerHTML.slice(-500)]); })()));
await p.getByRole('button', { name: 'Ask Sen', exact: true }).click();
await p.waitForTimeout(2500);
const r = await new AxeBuilder({ page: p }).withTags(['wcag2a','wcag2aa']).analyze();
for (const v of r.violations) console.log(v.id, JSON.stringify(v.nodes.map(n => [n.any.map(c=>c.message), n.none.map(c=>c.message), n.failureSummary])));
await b.close();
